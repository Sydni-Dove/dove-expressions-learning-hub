/** Generates the one-time import migration for the three original manuscripts. Run: WRITE_SEED=1 npx vite-node scripts/teaching-import/generate-seed.ts
 *  The imported teachings arrive as READY FOR REVIEW (never published, never assigned). After this migration the database is the only source of truth. */
import fs from "node:fs";
import { TEACHING_MODULES } from "./index";
import { IMPORT_CATEGORIES, toPayload } from "./convert";

export const SEED_FILE = "supabase/migrations/20261102100000_dp_voice_worship_teachings_seed.sql";
const tag = (s: string) => { let t = "j"; while (s.includes(`$${t}$`)) t += "x"; return `$${t}$`; };
const lit = (s: string) => { const t = tag(s); return `${t}${s}${t}`; };
export function buildTeachingSeedSql(): string {
  const out = [
    "-- GENERATED by scripts/teaching-import/generate-seed.ts from the original manuscripts. Do not edit by hand.",
    "-- ADDITIVE ONLY and NOT YET APPLIED. Apply after 20261102090000. Imports the three manuscripts as READY FOR REVIEW. Nothing is published, assigned or enrolled.",
    "-- Idempotent: a teaching that already exists (by key) is left untouched, so re-running can never overwrite edits made in the Teaching Editor.", ""
  ];
  for (const m of TEACHING_MODULES) {
    const pl = toPayload(m); const k = lit(m.key);
    out.push(`do $import$ declare tid uuid; begin`);
    out.push(` if exists(select 1 from dp_voice_teachings where key=${k}) then return; end if;`);
    out.push(` tid:=gen_random_uuid();`);
    out.push(` insert into dp_voice_teachings(id,key,status,template,sort_order) values(tid,${k},'ready_for_review','imported',${m.number});`);
    out.push(` insert into dp_voice_teaching_drafts(teaching_id,title,description,estimated_minutes,objectives,student,instructor) values(tid,${lit(pl.title)},${lit(pl.description)},${pl.estimated_minutes},${lit(JSON.stringify(pl.objectives))}::jsonb,${lit(JSON.stringify(pl.student))}::jsonb,${lit(JSON.stringify(pl.instructor))}::jsonb);`);
    out.push(` insert into dp_voice_teaching_category_links(teaching_id,category_id) select tid,id from dp_voice_teaching_categories where slug in (${IMPORT_CATEGORIES[m.key].map(lit).join(",")});`);
    out.push(` insert into dp_voice_teaching_revisions(teaching_id,rev_no,reason,label,title,description,estimated_minutes,objectives,student,instructor) select tid,1,'imported','Imported from the original manuscript',title,description,estimated_minutes,objectives,student,instructor from dp_voice_teaching_drafts where teaching_id=tid;`);
    out.push(`end $import$;`, "");
  }
  return out.join("\n");
}
if (process.env.WRITE_SEED) { fs.writeFileSync(SEED_FILE, buildTeachingSeedSql()); console.log("wrote teaching seed"); }
