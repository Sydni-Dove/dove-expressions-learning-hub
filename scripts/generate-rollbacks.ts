/**
 * Generates one rollback script per UNAPPLIED Voice migration by diffing the schema before and after each one in an in-memory Postgres.
 * Run: WRITE_ROLLBACKS=1 npx vite-node scripts/generate-rollbacks.ts
 * The scripts are committed (supabase/rollback/) and verified by tests/sql/rollback.test.ts. Nothing here touches any real database.
 */
import fs from "node:fs";
import path from "node:path";
import { createBareDb } from "../tests/sql/harness";
import { diff, snapshot, type Snapshot } from "../tests/sql/snapshot";

export const VOICE_MIGRATIONS = [
  "20261029090000_dp_voice_recordings_scheduling_consultations.sql", "20261029100000_dp_voice_draft_lesson_content.sql", "20261029110000_dp_voice_student_resources.sql",
  "20261030090000_dp_voice_practice_recordings.sql", "20261030100000_dp_voice_intake_assessments_plans.sql", "20261030110000_dp_voice_curriculum_seed.sql",
  "20261031090000_dp_voice_plan_revisions_ratings_imports.sql", "20261101090000_dp_voice_onboarding_payment_access.sql"
];
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const tbl = (k: string) => k.replace(/^public\./, "");

function aclGrants(fn: string, acl: string) {
  const out = [`revoke all on function ${fn} from public, anon, authenticated, service_role;`];
  for (const e of acl.replace(/[{}"]/g, "").split(",").filter(Boolean)) {
    const [who, rest] = e.split("="); const privs = (rest ?? "").split("/")[0];
    if (privs.includes("X")) out.push(`grant execute on function ${fn} to ${who === "" ? "public" : who};`);
  }
  return out;
}

export function buildRollback(version: string, before: Snapshot, after: Snapshot, extra: { dataSql?: string[]; warnings?: string[] } = {}) {
  const d = diff(before, after); const L: string[] = []; const manual: string[] = [];
  const newTables = new Set(d.tablesAdded.map(tbl));
  const persists = (key: string) => !newTables.has(key.split(".")[0]);
  L.push("begin;");
  for (const k of d.policiesAdded) { const [schema, table, ...p] = k.split("."); if (persists(table) || schema === "storage") L.push(`drop policy if exists "${p.join(".")}" on ${schema}.${table};`); }
  for (const k of d.triggersAdded) { const [table, name] = k.split("."); if (persists(table)) L.push(`drop trigger if exists ${name} on ${table};`); }
  for (const k of d.policiesChanged.concat(d.policiesRemoved)) { const [schema, table, ...p] = k.split("."); L.push(`drop policy if exists "${p.join(".")}" on ${schema}.${table};`, before.policyDefs[k]); }
  for (const k of d.triggersRemoved.concat(d.triggersChanged, d.indexesRemoved, d.indexesChanged, d.columnsRemoved, d.columnsChanged, d.rlsChanged, d.tablesRemoved, d.bucketsRemoved, d.bucketsChanged, d.typesRemoved)) manual.push(k);
  for (const k of d.constraintsChanged) { const i = k.lastIndexOf("."); const t = k.slice(0, i), c = k.slice(i + 1); L.push(`alter table ${t} drop constraint ${c};`, `alter table ${t} add constraint ${c} ${before.constraints[k]};`); }
  for (const k of d.constraintsAdded) { const i = k.lastIndexOf("."); const t = k.slice(0, i), c = k.slice(i + 1); if (persists(t)) L.push(`alter table ${t} drop constraint if exists ${c};`); }
  for (const k of d.constraintsRemoved) { const i = k.lastIndexOf("."); const t = k.slice(0, i); if (persists(t)) manual.push(k); }
  for (const s of extra.dataSql ?? []) L.push(s);
  const views = d.tablesAdded.filter((k) => after.tables[k].kind === "v"), realTables = d.tablesAdded.filter((k) => after.tables[k].kind !== "v");
  for (const v of views.reverse()) L.push(`drop view if exists ${tbl(v)};`);
  if (realTables.length) L.push(`drop table if exists ${[...realTables].reverse().map(tbl).join(", ")} cascade;`);
  for (const k of d.columnsAdded) { const i = k.indexOf("."); const t = k.slice(0, i), c = k.slice(i + 1); if (persists(t)) L.push(`alter table ${t} drop column if exists ${c} cascade;`); }
  for (const k of d.indexesAdded) { const [t, name] = k.split("."); const isConstraint = d.constraintsAdded.some((c) => c.endsWith("." + name)); if (persists(t) && !isConstraint) L.push(`drop index if exists ${name};`); }
  for (const k of d.functionsAdded) L.push(`drop function if exists ${k};`);
  for (const k of d.functionsChanged) { L.push(before.functions[k].def.trim().replace(/;?$/, ";")); L.push(...aclGrants(k, before.functions[k].acl)); }
  for (const k of d.functionsRemoved) { L.push(before.functions[k].def.trim().replace(/;?$/, ";")); L.push(...aclGrants(k, before.functions[k].acl)); }
  for (const t of d.typesAdded) L.push(`drop type if exists ${t};`);
  if (d.bucketsAdded.length) L.push(`-- Storage buckets can be removed only when empty. Empty them through the Storage API first (never with SQL).`, `delete from storage.buckets where id in (${d.bucketsAdded.map(q).join(", ")});`);
  L.push("commit;");
  const header = [
    `-- ROLLBACK for ${version}. GENERATED by scripts/generate-rollbacks.ts from a before/after schema diff; verified by tests/sql/rollback.test.ts.`,
    `-- NOT RUN anywhere. Read docs/voice-release-plan.md first: take a backup, export new-table data you want to keep, and roll back in REVERSE order.`,
    `-- Runs in one transaction: if anything fails, nothing changes.`,
    ...(extra.warnings ?? []).map((w) => `-- WARNING: ${w}`),
    ...(manual.length ? [`-- MANUAL STEPS NEEDED (the generator found changes it cannot reverse automatically): ${manual.join("; ")}`] : []), ""
  ];
  return { sql: header.concat(L).join("\n") + "\n", manual, d };
}

export async function planAll() {
  const { db, files, apply } = await createBareDb();
  const base = files.filter((f) => !VOICE_MIGRATIONS.includes(f));
  for (const f of base) await apply(f);
  const results: { file: string; sql: string; manual: string[]; before: Snapshot; after: Snapshot }[] = [];
  let before = await snapshot(db);
  const dir = path.join(__dirname, "../supabase/migrations");
  for (const file of VOICE_MIGRATIONS) {
    const extra: { dataSql?: string[]; warnings?: string[] } = { dataSql: [], warnings: [] };
    const skillsBefore = file.startsWith("20261030110000") ? (await db.query<any>("select slug from dp_voice_skills")).rows.map((r) => r.slug) : [];
    await apply(file);
    const after = await snapshot(db);
    if (file.startsWith("20261029100000")) {
      const sql = fs.readFileSync(path.join(dir, file), "utf8");
      const rows = [...sql.matchAll(/\('([a-z-]+)','(teaching_section|takeaways)',(\d+),\$j\$([\s\S]*?)\$j\$::jsonb\)/g)].map((m) => `(${q(m[1])},${q(m[2])},${m[3]},${q(m[4])})`);
      extra.dataSql!.push(`-- Removes only the draft blocks this migration inserted, and only if nobody has edited them (content must still match exactly).`,
        `delete from dp_lesson_blocks b using dp_lessons l, (values ${rows.join(",\n ")}) v(slug,bt,oi,body) where l.id=b.lesson_id and l.slug=v.slug and b.block_type=v.bt and b.order_index=v.oi and b.content=v.body::jsonb;`);
      extra.warnings!.push("Draft blocks an instructor has edited are kept on purpose.");
    }
    if (file.startsWith("20261030110000")) {
      const added = (await db.query<any>("select slug from dp_voice_skills")).rows.map((r) => r.slug).filter((s) => !skillsBefore.includes(s));
      extra.dataSql!.push(`-- Removes the seeded exercise library and the skills the seed added. Exercises already ASSIGNED to students are copied into their assignments and are not affected.`,
        `delete from dp_voice_exercises where curriculum_key is not null;`,
        `delete from dp_voice_skills s where s.slug in (${added.map(q).join(", ")}) and not exists (select 1 from dp_voice_exercises e where e.skill_id=s.id);`);
    }
    if (file.startsWith("20261029090000")) extra.warnings!.push("Dropping the recording/testimonial tables deletes their rows. Export them first; storage objects must be removed through the Storage API.");
    if (file.startsWith("20261029110000")) extra.warnings!.push("This migration also ran 'revoke all on all functions in schema dp_private from public, anon' and granted execute on them to authenticated. That blanket change cannot be reversed from a diff; restore from the ACL snapshot taken before applying (see docs/voice-release-plan.md).");
    if (file.startsWith("20261030090000")) extra.warnings!.push("Dropping dp_practice_recordings loses the link to student recordings stored in R2. Export the object keys and remove the R2 objects separately.");
    if (file.startsWith("20261030100000")) extra.warnings!.push("Dropping these tables deletes every intake, assessment answer, plan and progress check. Export first.");
    const r = buildRollback(file.replace(/\.sql$/, ""), before, after, extra);
    results.push({ file, sql: r.sql, manual: r.manual, before, after });
    before = after;
  }
  return { db, results };
}

if (process.env.WRITE_ROLLBACKS) {
  planAll().then(({ results }) => {
    fs.mkdirSync("supabase/rollback", { recursive: true });
    for (const r of results) fs.writeFileSync(`supabase/rollback/${r.file.replace(/\.sql$/, "")}.rollback.sql`, r.sql);
    console.log(results.map((r) => `${r.file}: ${r.sql.split("\n").length} lines${r.manual.length ? " MANUAL: " + r.manual.join(", ") : ""}`).join("\n"));
  });
}
