/** Generates the Worship Development seed migration from lib/voice-teaching (the single source). Run: WRITE_SEED=1 npx vite-node scripts/generate-teaching-seed.ts */
import fs from "node:fs";
import { TEACHING_MODULES } from "../lib/voice-teaching";

export const SEED_FILE = "supabase/migrations/20261102100000_dp_voice_worship_teachings_seed.sql";
const tag = (s: string) => { let t = "j"; while (s.includes(`$${t}$`)) t += "x"; return `$${t}$`; };
const lit = (s: string) => { const t = tag(s); return `${t}${s}${t}`; };
export function buildTeachingSeedSql(): string {
  const out = [
    "-- GENERATED by scripts/generate-teaching-seed.ts from lib/voice-teaching. Do not edit by hand; change the source and regenerate.",
    "-- ADDITIVE ONLY and NOT YET APPLIED. Apply after 20261102090000. Seeds the Worship Development library; nothing is assigned or enrolled.", ""
  ];
  for (const m of TEACHING_MODULES) {
    const student = { objectives: m.objectives, scriptures: m.scriptures, ...m.student };
    out.push(`insert into dp_voice_teaching_modules(key,module_number,title,summary,main_message,estimated_minutes,student_content) values`);
    out.push(` (${lit(m.key)},${m.number},${lit(m.title)},${lit(m.summary)},${lit(m.mainMessage)},${m.estimatedMinutes},${lit(JSON.stringify(student))}::jsonb)`);
    out.push(`on conflict (key) do nothing;`);
    out.push(`insert into dp_voice_teaching_module_private(module_id,instructor_notes) select id,${lit(JSON.stringify(m.instructor))}::jsonb from dp_voice_teaching_modules where key=${lit(m.key)}`);
    out.push(`on conflict (module_id) do nothing;`, "");
  }
  return out.join("\n");
}
if (process.env.WRITE_SEED) { fs.writeFileSync(SEED_FILE, buildTeachingSeedSql()); console.log("wrote teaching seed"); }
